/**
 * Writes the public client config consumed by the React Native bundle.
 * Refuses to embed privileged backend secrets even if they are present in the environment.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(here, '../src/config/public-env.generated.ts');

const forbidden = [
  'SUPABASE_SERVICE_ROLE_KEY',
  'AI_OPENROUTER_API_KEY',
  'OPENROUTER_API_KEY',
  'AI_GEMINI_API_KEY',
  'GEMINI_API_KEY',
  'AI_GROQ_API_KEY',
  'GROQ_API_KEY',
];

for (const key of forbidden) {
  if (process.env[`SHARPMIND_EMBED_${key}`]) {
    console.error(`[mobile] Refusing to embed privileged secret ${key} into the client.`);
    process.exit(1);
  }
}

const read = (...keys) => {
  for (const key of keys) {
    const value = process.env[key];
    if (value && value.trim()) {
      return value.trim();
    }
  }
  return '';
};

const config = {
  supabaseUrl: read('SHARPMIND_SUPABASE_URL', 'NEXT_PUBLIC_SUPABASE_URL'),
  supabaseAnonKey: read('SHARPMIND_SUPABASE_ANON_KEY', 'NEXT_PUBLIC_SUPABASE_ANON_KEY'),
  apiUrl: read('SHARPMIND_API_URL', 'NEXT_PUBLIC_API_URL'),
  appEnv: read('SHARPMIND_APP_ENV') || 'debug',
};

const body = `/* Generated by scripts/write-public-config.mjs. Do not commit real secrets. */
export const generatedPublicEnv: {
  supabaseUrl: string;
  supabaseAnonKey: string;
  apiUrl: string;
  appEnv: string;
} = ${JSON.stringify(config, null, 2)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body);
console.log(`[mobile] Wrote public config (${config.supabaseUrl ? 'supabase set' : 'supabase missing'}, ${config.apiUrl ? 'api set' : 'api missing'}).`);
